export const getTranslation = (lang, key) => {
    const l = lang ? lang.toUpperCase() : 'PT';
    const dict = UI_TRANSLATIONS[l] || UI_TRANSLATIONS['PT'];
    return dict[key] || UI_TRANSLATIONS['PT'][key] || key;
};

